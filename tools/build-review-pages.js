// Generates a static copy of movie.html for every reviewed title at /review/<mediaId>/
// with real <title>, description, canonical, Open Graph and Twitter tags baked in, so
// link previews (iMessage, Instagram DMs, Discord, X) and search crawlers see the title
// instead of the generic card. Also adds those URLs to sitemap.xml.
//
// Runs in the Pages deploy workflow before upload. Reads Firebase over the public REST
// API, so it needs no credentials and no npm install.
//
//   node tools/build-review-pages.js

import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { games } from '../Assets/scripts/games.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://truerated.co';
const DB = 'https://mediareviews-3cf32-default-rtdb.firebaseio.com';
const OUT_DIR = 'review';
const DEFAULT_IMAGE = `${SITE}/Assets/images/cardimage.jpg`;
const KNOWN_CATEGORIES = ['movies', 'tv', 'books', 'games', 'music'];
const SITEMAP_START = '  <!-- review pages: generated by tools/build-review-pages.js -->';
const SITEMAP_END = '  <!-- /review pages -->';

async function dbGet(path) {
    const res = await fetch(`${DB}/${path}.json`);
    if (!res.ok) throw new Error(`GET /${path} → ${res.status}`);
    return (await res.json()) || {};
}

function readJson(file) {
    try {
        // Some data files are saved with a UTF-8 BOM
        return JSON.parse(readFileSync(join(ROOT, file), 'utf8').replace(/^﻿/, ''));
    } catch (e) {
        console.warn(`Could not read ${file}: ${e.message}`);
        return [];
    }
}

const slugify = title => (title || '').trim().replace(/[^a-zA-Z0-9]/g, '_').toLowerCase();

function stripCategoryPrefix(mediaId) {
    for (const cat of KNOWN_CATEGORIES) {
        if (mediaId.startsWith(cat + '_')) return mediaId.slice(cat.length + 1);
    }
    return mediaId;
}

// Same matching rules as reviewDetails.js so the static tags agree with the rendered page
function findMedia(allMedia, mediaId, reviewYear) {
    const slugOnly = stripCategoryPrefix(mediaId);
    return allMedia.reduce((best, m) => {
        const mId = slugify(m.title);
        if (mId !== mediaId && mId !== slugOnly && m.id != mediaId) return best;
        if (!best) return m;
        if (reviewYear && String(m.year) === String(reviewYear)) return m;
        if (reviewYear && String(best.year) === String(reviewYear)) return best;
        return (parseInt(m.year) || 0) > (parseInt(best.year) || 0) ? m : best;
    }, null);
}

const escapeAttr = s => String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function plainText(html) {
    return String(html || '')
        .replace(/<br\s*\/?>|<\/p>|<\/div>/gi, ' ')
        .replace(/<[^>]*>/g, '')
        .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
        .replace(/\s+/g, ' ')
        .trim();
}

function truncate(s, max) {
    if (s.length <= max) return s;
    return s.slice(0, max - 1).replace(/\s+\S*$/, '') + '…';
}

function absoluteImage(url) {
    if (!url) return DEFAULT_IMAGE;
    if (/^https?:\/\//.test(url)) return url;
    if (url.startsWith('//')) return 'https:' + url;
    return DEFAULT_IMAGE; // relative paths in the data files point at placeholders
}

// Sets one attribute on the element with the given id. Throws if movie.html changed shape,
// so a broken template fails the build instead of shipping generic previews.
function setById(html, id, attr, value) {
    const re = new RegExp(`(<[^>]*\\bid="${id}"[^>]*\\b${attr}=")[^"]*(")`);
    if (!re.test(html)) throw new Error(`movie.html: no ${attr} on #${id}`);
    return html.replace(re, `$1${escapeAttr(value)}$2`);
}

function buildPage(template, { mediaId, title, description, image, url }) {
    const pageTitle = `${title} — Review | True Rated`;
    let html = template;
    // Pages live at /review/<id>/, so resolve the template's relative URLs from the site root
    html = html.replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n    <base href="/">');
    html = html.replace(/<title>[^<]*<\/title>/, `<title>${escapeAttr(pageTitle)}</title>`);
    html = setById(html, 'meta-description', 'content', description);
    html = setById(html, 'canonical', 'href', url);
    html = setById(html, 'og-title', 'content', pageTitle);
    html = setById(html, 'og-description', 'content', description);
    html = setById(html, 'og-url', 'content', url);
    html = setById(html, 'og-image', 'content', image);
    html = setById(html, 'tw-title', 'content', pageTitle);
    html = setById(html, 'tw-description', 'content', description);
    html = setById(html, 'tw-image', 'content', image);
    html = html.replace(/<body([^>]*)>/, `<body$1 data-media-id="${escapeAttr(mediaId)}">`);
    return html;
}

function updateSitemap(entries) {
    const file = join(ROOT, 'sitemap.xml');
    let xml = readFileSync(file, 'utf8');
    const startIdx = xml.indexOf(SITEMAP_START);
    if (startIdx !== -1) {
        const endIdx = xml.indexOf(SITEMAP_END, startIdx);
        xml = xml.slice(0, startIdx) + xml.slice(endIdx + SITEMAP_END.length + 1);
    }
    const urls = entries.map(({ url, lastmod }) => [
        '  <url>',
        `    <loc>${escapeAttr(url)}</loc>`,
        lastmod ? `    <lastmod>${lastmod}</lastmod>` : null,
        '    <changefreq>weekly</changefreq>',
        '    <priority>0.8</priority>',
        '  </url>',
    ].filter(Boolean).join('\n')).join('\n\n');
    const block = `${SITEMAP_START}\n\n${urls}\n\n${SITEMAP_END}\n`;
    xml = xml.replace('</urlset>', `${block}\n</urlset>`);
    writeFileSync(file, xml);
}

async function main() {
    let reviews, reviewers, tmdbMovies;
    try {
        [reviews, reviewers, tmdbMovies] = await Promise.all([
            dbGet('reviews'), dbGet('reviewers'), dbGet('tmdb_movies'),
        ]);
    } catch (e) {
        // Don't block the deploy; the site still works through movie.html?id=
        console.log(`::warning::Skipping review pages, Firebase read failed: ${e.message}`);
        return;
    }

    const movies = Object.keys(tmdbMovies).length
        ? Object.values(tmdbMovies)
        : readJson('Assets/Data/movieList.json');
    const allMedia = [
        ...movies,
        ...readJson('Assets/Data/tvList.json'),
        ...readJson('Assets/Data/books.json'),
        ...readJson('Assets/Data/musicList.json'),
        ...games,
    ];

    const template = readFileSync(join(ROOT, 'movie.html'), 'utf8');
    rmSync(join(ROOT, OUT_DIR), { recursive: true, force: true });

    const sitemapEntries = [];
    for (const [mediaId, byKey] of Object.entries(reviews)) {
        // Directory names must be safe; Firebase keys can't hold / anyway
        if (!/^[A-Za-z0-9_-]+$/.test(mediaId) || !byKey || typeof byKey !== 'object') continue;
        const list = Object.values(byKey).filter(r => r && typeof r === 'object');
        if (!list.length) continue;

        const review = list[0]; // movie.html shows the first review
        const media = findMedia(allMedia, mediaId, review.mediaYear || null);
        const title = media?.title || stripCategoryPrefix(review.mediaId || mediaId).replace(/_/g, ' ');
        const reviewer = reviewers[review.userId]?.name || 'a True Rated critic';
        const reviewText = review.spoilers ? '' : plainText(review.reviewText || review.text);
        const rating = review.rating ? `Rated ${review.rating}/10 by ${reviewer}.` : `Reviewed by ${reviewer}.`;
        const description = truncate(
            reviewText ? `${rating} "${reviewText}"`
                : `${rating} ${media?.description || `Read the review of ${title} on True Rated.`}`,
            200,
        );
        const url = `${SITE}/${OUT_DIR}/${mediaId}/`;

        const dir = join(ROOT, OUT_DIR, mediaId);
        mkdirSync(dir, { recursive: true });
        writeFileSync(join(dir, 'index.html'), buildPage(template, {
            mediaId, title, description, url,
            image: absoluteImage(media?.poster || media?.image),
        }));

        const newest = Math.max(0, ...list.map(r => Date.parse(r.timestamp)).filter(Number.isFinite));
        sitemapEntries.push({ url, lastmod: newest ? new Date(newest).toISOString().slice(0, 10) : null });
    }

    updateSitemap(sitemapEntries);
    console.log(`Wrote ${sitemapEntries.length} review pages to /${OUT_DIR}/ and sitemap.xml`);
}

main().catch(e => {
    console.error(e);
    process.exit(1);
});
